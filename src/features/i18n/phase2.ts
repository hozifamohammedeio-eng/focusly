export function subjectLabel(copy: Copy, value: string): string {
  if (Object.hasOwn(copy.subjectNames, value))
    return copy.subjectNames[value as keyof Copy["subjectNames"]];
  const subject = Object.values(LABELS).find(labels => labels[0] === value);
  if (subject) return subject[copy.login === "Log In" ? 0 : 1];
  return value;
}
